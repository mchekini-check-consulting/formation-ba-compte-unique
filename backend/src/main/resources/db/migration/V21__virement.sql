-- CU-147 (US-21) : virement depuis le compte courant vers un bénéficiaire actif (CU-146), signé par un code SMS.
-- Nom et IBAN du bénéficiaire recopiés au moment du virement : un bénéficiaire supprimé plus tard ne change pas
-- l'historique. Code haché (jamais en clair), valable 5 minutes, à usage unique, 3 essais.
create table virement (
    id                 bigint generated by default as identity primary key,
    compte_id          bigint       not null references compte (id),
    beneficiaire_id    bigint       not null references beneficiaire (id),
    nom_beneficiaire   varchar(70)  not null,
    iban_beneficiaire  varchar(34)  not null,
    montant_centimes   bigint       not null check (montant_centimes > 0),
    libelle            varchar(140) not null,
    statut             varchar(30)  not null,   -- EN_ATTENTE_SIGNATURE, EXECUTE, REFUSE, ANNULE
    motif_refus        varchar(140),
    cree_le            timestamp with time zone not null,
    execute_le         timestamp with time zone,
    code_hache         varchar(100) not null,
    code_envoye_le     timestamp with time zone not null,
    codes_faux         integer      not null default 0
);

create index virement_compte on virement (compte_id);
create index virement_beneficiaire on virement (beneficiaire_id, statut);

-- Le mouvement de débit (et de recrédit si la banque destinataire refuse) pointe vers son virement.
alter table mouvement add column virement_id bigint references virement (id);

-- Nouveau type de mouvement : recrédit d'un virement refusé par la banque destinataire, avec le bénéficiaire.
alter table mouvement drop constraint mouvement_contrepartie;
alter table mouvement
    add constraint mouvement_contrepartie check (
        (type = 'VIREMENT_ENTRANT' and emetteur is not null)
        or (type in ('VIREMENT_SORTANT', 'RECREDIT_VIREMENT')
            and beneficiaire is not null and iban_beneficiaire is not null)
    );
