-- CU-311 (PER-02) et CU-331 (AV-02) : documents à lire avant de souscrire un PER ou une assurance vie.
-- ADR-001 : module Découverte, ses tables vivent dans le schéma decouverte.

create schema if not exists decouverte;

-- Une ligne par ouverture d'un document, jamais effacée. Cocher « J'ai pris connaissance » remplit coche_le sur la
-- dernière ouverture ; la case reste valable tant que la version du document ne change pas.
create table decouverte.consultation_document (
    id               bigint generated by default as identity primary key,
    customer_id      uuid                     not null,
    -- PER ou AV
    produit          varchar(3)               not null,
    -- DIC ou FICHE_PRODUIT
    document         varchar(20)              not null,
    version_document varchar(30)              not null,
    -- date et heure métier (TECH-12)
    ouvert_le        timestamp with time zone not null,
    coche_le         timestamp with time zone
);

create index consultation_document_cliente on decouverte.consultation_document (customer_id, produit, document);
