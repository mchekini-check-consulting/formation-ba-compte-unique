-- CU-314 (PER-07) et CU-338 (AV-07) : mode de gestion (libre, pilotée, sous mandat) et profil de gestion d'un
-- contrat PER ou assurance vie. ADR-001 : module Gestion, ses tables vivent dans le schéma gestion ; les autres
-- modules appellent ModeDeGestion. En attendant PER-04 et AV-01, les contrats sont des contrats de test (décision BA
-- du 26/11/2026).

create schema if not exists gestion;

-- Mode et profil de gestion en vigueur d'un contrat (une ligne par contrat, une cliente a au plus un contrat par produit).
create table gestion.contrat_gestion (
    id             bigint generated by default as identity primary key,
    numero_contrat varchar(30)              not null unique,
    customer_id    uuid                     not null,
    -- PER ou AV
    produit        varchar(3)               not null,
    -- LIBRE, PILOTEE ou MANDAT
    mode           varchar(10)              not null,
    -- PRUDENT, EQUILIBRE ou DYNAMIQUE
    profil         varchar(20)              not null,
    -- PER : année prévue de départ à la retraite (profil client, CU-10), qui donne l'horizon
    annee_depart_retraite integer,
    cree_le        timestamp with time zone not null,
    -- date et heure métier du dernier changement (TECH-12)
    change_le      timestamp with time zone not null,
    unique (customer_id, produit)
);

-- Historique : une ligne par choix (création comprise), jamais modifiée. Changement toujours gratuit.
create table gestion.changement_gestion (
    id             bigint generated by default as identity primary key,
    numero_contrat varchar(30)              not null,
    mode           varchar(10)              not null,
    profil         varchar(20)              not null,
    -- PER : nombre d'années avant la retraite au moment du choix
    horizon_annees integer,
    frais          numeric(15, 2)           not null default 0,
    change_le      timestamp with time zone not null
);

create index changement_gestion_contrat on gestion.changement_gestion (numero_contrat);

-- Paramètres de la gestion sous mandat, par produit (décisions PO des 22 et 23/11/2026, minimum à valider par le métier).
create table gestion.parametre_mandat (
    produit                varchar(3)               primary key,
    taux_tout_compris_pct  numeric(5, 2)            not null check (taux_tout_compris_pct >= 0),
    montant_minimum        numeric(15, 2)           not null check (montant_minimum >= 0),
    modifie_le             timestamp with time zone not null
);

