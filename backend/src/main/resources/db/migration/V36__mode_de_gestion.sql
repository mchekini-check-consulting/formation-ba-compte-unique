-- Rééquilibrage au passage en gestion pilotée : arbitrages internes gratuits, exécutés au prochain cours.
create table gestion.reequilibrage (
    id              bigint generated by default as identity primary key,
    numero_contrat  varchar(30)              not null,
    demande_le      timestamp with time zone not null,
    montant_arbitre numeric(15, 2)           not null
);

create index reequilibrage_contrat on gestion.reequilibrage (numero_contrat);

-- Un arbitrage du rééquilibrage, avec l'ordre passé au module Ordres.
create table gestion.reequilibrage_ordre (
    id               bigint generated by default as identity primary key,
    reequilibrage_id bigint         not null references gestion.reequilibrage (id),
    ordre_id         uuid           not null,
    support_depart   varchar(12)    not null,
    support_arrivee  varchar(12)    not null,
    montant          numeric(15, 2) not null
);

-- Frais de la gestion sous mandat, calculés et enregistrés sans prélèvement (PER-24 et une story AV les prélèveront
-- après TECH-10) : la cliente paie le taux tout compris, l'établissement prend l'écart.
create table gestion.frais_mandat (
    id                    bigint generated by default as identity primary key,
    numero_contrat        varchar(30)              not null,
    calcule_le            timestamp with time zone not null,
    encours               numeric(15, 2)           not null,
    taux_tout_compris_pct numeric(5, 2)            not null,
    frais_cliente         numeric(15, 2)           not null,
    cout_reel_supports    numeric(15, 2)           not null,
    ecart_etablissement   numeric(15, 2)           not null
);

create index frais_mandat_contrat on gestion.frais_mandat (numero_contrat);

-- AV-07 (décision PO du 26/11/2026) : au passage en gestion pilotée, les supports non cotés existants restent dans le
-- contrat, hors gestion pilotée. Chacun dont le niveau de risque dépasse le maximum du profil de gestion choisi
-- (prudent 3, équilibré 4, dynamique 6) est signalé au back-office, à traiter.
create table gestion.signalement_non_cote (
    id             bigint generated by default as identity primary key,
    numero_contrat varchar(30)              not null,
    code_isin      varchar(12)              not null,
    montant        numeric(15, 2)           not null,
    niveau_risque  smallint                 not null,
    -- profil de gestion choisi (PRUDENT, EQUILIBRE, DYNAMIQUE)
    profil         varchar(20)              not null,
    signale_le     timestamp with time zone not null,
    -- A_TRAITER à l'enregistrement
    statut         varchar(20)              not null
);

create index signalement_non_cote_statut on gestion.signalement_non_cote (statut);
