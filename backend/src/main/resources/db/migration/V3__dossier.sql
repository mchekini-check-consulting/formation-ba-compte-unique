-- Dossier d'ouverture de compte (CUB-8, US-01 « Renseigner mon identité et passer les contrôles »).
-- Une ligne par demande d'ouverture en ligne, repérée par la référence générée par l'écran.
-- Enregistré : identité saisie et date de saisie, catégories du pays de naissance et de la
-- nationalité, indice américain (FATCA), résidence française déduite du type de pièce,
-- résultat des contrôles sanctions et PEP avec leur date, statut du dossier.
create table dossier (
    id                    bigint generated by default as identity primary key,
    reference             varchar(64)  not null unique,
    civilite              varchar(5)   not null,
    nom_naissance         varchar(100) not null,
    nom_usage             varchar(100),
    prenoms               varchar(200) not null,
    date_naissance        date         not null,
    commune_naissance     varchar(100) not null,
    pays_naissance        varchar(20)  not null,  -- FRANCE, UE_HORS_FRANCE, HORS_UE, ETATS_UNIS
    indice_americain      boolean      not null,  -- FATCA : né(e) aux États-Unis
    nationalite           varchar(20)  not null,  -- FRANCE, UE_HORS_FRANCE, HORS_UE
    voie                  varchar(200) not null,
    complement_adresse    varchar(200),
    code_postal           varchar(10)  not null,
    ville                 varchar(100) not null,
    pays_adresse          varchar(60)  not null,
    email                 varchar(254) not null,
    mobile                varchar(20)  not null,
    fixe                  varchar(20),
    type_piece            varchar(30)  not null,  -- CARTE_NATIONALE_IDENTITE, TITRE_SEJOUR
    numero_piece          varchar(30)  not null,
    date_expiration_piece date         not null,
    residence_francaise   boolean      not null,
    saisi_le              timestamp with time zone not null,
    controle_sanctions    varchar(3),             -- OK, NOK ; vide tant que le contrôle n'a pas répondu
    controle_pep          varchar(3),
    controle_le           timestamp with time zone,
    statut                varchar(30)  not null   -- EN_COURS_DE_VERIFICATION, ACCEPTE, ANNULE
);
