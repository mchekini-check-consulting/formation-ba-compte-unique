-- CU-12 (US-07) : signature de la convention de compte avec un code reçu par SMS (Docusign).
-- Une ligne par dossier : la signature reprend au même endroit si la cliente revient.
create table signature_convention (
    id                  bigint generated by default as identity primary key,
    dossier_id          bigint      not null unique references dossier (id),
    enveloppe_id        varchar(64) not null,   -- enveloppe Docusign en cours (nouvelle à chaque relance)
    statut_enveloppe    varchar(20) not null,   -- ENVOYEE, EXPIREE, SIGNEE, ANNULEE
    empreinte_document  varchar(64) not null,   -- SHA-256 de la convention présentée
    code_envoye_le      timestamp with time zone not null,
    codes_faux          integer     not null default 0,
    relances            integer     not null default 0,
    signee_le           timestamp with time zone,
    motif_annulation    varchar(40)             -- Code expiré, 3 tentatives dépassées, Annulation demandée
);
