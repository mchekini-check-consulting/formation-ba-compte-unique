-- CU-29 (US-20, avec ex-CU-30 / US-21) : nouvelle pièce d'identité et vérification de présence à l'ouverture
-- d'un Livret A, quand la pièce du dossier client a expiré. Une ligne par vérification : pièce saisie par la
-- cliente, résultat de l'analyse Stripe Identity, puis résultat et score du selfie. La pièce ne remplace celle du
-- dossier qu'une fois les deux vérifications réussies (statut VALIDE).
create table piece_identite_livret_a (
    id                   bigint generated by default as identity primary key,
    reference            varchar(64) not null unique,
    dossier_id           bigint      not null references dossier (id),
    customer_id          uuid        not null,
    -- PIECE_A_VERIFIER, SELFIE_A_FAIRE, VALIDE, BLOQUE, EN_ATTENTE
    statut               varchar(30) not null,
    -- CARTE_NATIONALE_IDENTITE, TITRE_SEJOUR, PASSEPORT
    type_piece           varchar(30) not null,
    numero_piece         varchar(30) not null,
    date_expiration      date        not null,
    -- VERIFIE, A_REPRENDRE, REJETE, ERREUR_TECHNIQUE, SANS_REPONSE
    resultat_document    varchar(30),
    tentatives_document  integer     not null default 0,
    document_le          timestamp with time zone,
    -- CORRESPONDANCE, NON_CORRESPONDANCE, ECHEC_VERIFICATION_PRESENCE, SANS_REPONSE
    resultat_selfie      varchar(30),
    score_selfie         integer,
    tentatives_selfie    integer     not null default 0,
    selfie_le            timestamp with time zone,
    conseiller_alerte_le timestamp with time zone,
    valide_le            timestamp with time zone,
    cree_le              timestamp with time zone not null
);

create index piece_identite_livret_a_customer on piece_identite_livret_a (customer_id);
