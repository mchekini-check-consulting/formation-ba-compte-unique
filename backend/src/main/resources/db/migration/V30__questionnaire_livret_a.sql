-- CU-32 (US-23) : étape « Questions et données » de l'ouverture d'un Livret A par une cliente connectée.
-- Réponses au questionnaire obligatoire, avec la version du texte d'information acceptée à ce moment-là.
-- L'acceptation elle-même est tracée dans le registre des consentements de CU-10 (profil_client.consentement).
-- Un questionnaire sert à une seule ouverture : il est rattaché à la demande quand elle est créée (éligibilité).
create table questionnaire_livret_a (
    id                        bigint generated by default as identity primary key,
    reference                 varchar(64)  not null unique,
    dossier_id                bigint       not null references dossier (id),
    customer_id               uuid         not null,
    -- PRECAUTION, PROJET, AUTRE
    objet_epargne             varchar(30)  not null,
    -- SALAIRE_REVENUS, EPARGNE_EXISTANTE, HERITAGE_DONATION, VENTE_BIEN, AUTRE
    origine_fonds             varchar(30)  not null,
    -- Seulement pour l'origine AUTRE.
    precision_origine         varchar(200),
    version_texte_information varchar(10)  not null,
    repondu_le                timestamp with time zone not null,
    -- Demande de Livret A ouverte avec ce questionnaire : un questionnaire ne sert qu'à une ouverture.
    demande_reference         varchar(64)
);

create index questionnaire_livret_a_customer on questionnaire_livret_a (customer_id);
