-- CU-376 (TECH-08) : enregistrement des ordres (versements, rachats, arbitrages), ADR-001 sections 2 à 4.
-- Module Ordres : ses tables vivent dans le schéma ordres ; les autres modules appellent OrdresService ou lisent
-- l'événement « ordre demandé » (topic des ordres, clé = numéro de contrat).

create schema if not exists ordres;

-- Un ordre par identifiant, créé par l'écran à la validation : un double envoi ne crée pas de second ordre.
-- Montant en euros. Statuts : DEMANDE, EN_COURS, EXECUTE, REJETE, ANNULE ; DEMANDE et EN_COURS bloquent le montant.
create table ordres.ordre (
    id                    uuid primary key,
    numero_contrat        varchar(30)              not null,
    -- VERSEMENT, RACHAT ou ARBITRAGE
    type                  varchar(20)              not null,
    -- support vendu (rachat, arbitrage) et support acheté (versement, arbitrage), codes ISIN
    support_depart        varchar(12),
    support_arrivee       varchar(12),
    montant               numeric(15, 2)           not null check (montant > 0),
    -- date et heure métier de la demande (TECH-12)
    demande_le            timestamp with time zone not null,
    -- date de la valeur liquidative sur laquelle l'ordre sera exécuté (heure limite)
    date_execution_prevue date                     not null,
    statut                varchar(20)              not null,
    motif_rejet           varchar(200),
    -- événement « ordre demandé » enregistré dans la même transaction (evenements.a_distribuer)
    evenement_id          uuid
);

-- Montant bloqué : ordres en cours d'un contrat sur un support vendu.
create index ordre_en_cours on ordres.ordre (numero_contrat, support_depart) where statut in ('DEMANDE', 'EN_COURS');

-- Positions de test (dev et qualif uniquement) : l'encours d'un contrat en attendant les positions de TECH-10.
-- Montant en euros ou nombre de parts (valorisé à la dernière valeur liquidative du catalogue).
create table ordres.position_test (
    id               bigint generated by default as identity primary key,
    numero_contrat   varchar(30)              not null,
    code_isin        varchar(12)              not null,
    montant          numeric(15, 2),
    nombre_parts     numeric(18, 6),
    enregistree_le   timestamp with time zone not null,
    check ((montant is null) <> (nombre_parts is null))
);

create index position_test_contrat on ordres.position_test (numero_contrat, code_isin);
