-- CU-381 (TECH-13) : chargement nocturne du catalogue des unités de compte et des valeurs liquidatives.
-- ADR-001 : module placement, ses tables vivent dans le schéma catalogue ; les autres modules appellent
-- CatalogueService (fonctions publiques) ou lisent l'événement « catalogue mis à jour ».

create schema if not exists catalogue;

-- Un support par code ISIN : les 15 colonnes du fichier, mises à jour à chaque chargement (jamais de doublon).
-- Un support absent du fichier n'est pas retiré : seul le statut « retire » le retire.
create table catalogue.support (
    id                 bigint generated by default as identity primary key,
    code_isin          varchar(12)              not null unique,
    nom                varchar(200)             not null,
    type               varchar(50)              not null,
    categorie          varchar(100)             not null,
    -- PER, AV ou PER|AV
    produits_ouverts   varchar(10)              not null,
    niveau_risque      smallint                 not null check (niveau_risque between 1 and 7),
    cote               boolean                  not null,
    frais_support_pct  numeric(7, 4)            not null,
    -- actif ou retire
    statut             varchar(10)              not null,
    valeur_liquidative numeric(18, 6)           not null check (valeur_liquidative > 0),
    date_vl            date                     not null,
    devise             varchar(3)               not null,
    periodicite_vl     varchar(30)              not null,
    label              varchar(100)             not null,
    societe_gestion    varchar(200)             not null,
    mis_a_jour_le      timestamp with time zone not null
);

-- Historique des valeurs liquidatives : une valeur par support et par date (rejouer un fichier n'ajoute rien).
create table catalogue.historique_vl (
    id                 bigint generated by default as identity primary key,
    support_id         bigint                   not null references catalogue.support (id),
    valeur_liquidative numeric(18, 6)           not null,
    date_vl            date                     not null,
    -- nom du fichier d'où vient la valeur
    source             varchar(100)             not null,
    unique (support_id, date_vl)
);

-- Fichiers déposés sur la page de test /test/catalogue (prototype : pas de dépôt fournisseur réel).
-- Le batch lit le dernier fichier déposé dont la date est la date métier du jour.
create table catalogue.fichier_depose (
    id           bigint generated by default as identity primary key,
    nom_fichier  varchar(100)             not null,
    date_fichier date                     not null,
    contenu      text                     not null,
    depose_le    timestamp with time zone not null
);

create index fichier_depose_date on catalogue.fichier_depose (date_fichier);

-- Journal du batch : une ligne par exécution (automatique à l'heure du batch, ou manuelle depuis la page de test).
create table catalogue.journal_batch (
    id              bigint generated by default as identity primary key,
    date_metier     date                     not null,
    -- AUTOMATIQUE ou MANUEL
    declenchement   varchar(12)              not null,
    nom_fichier     varchar(100)             not null,
    debut           timestamp with time zone not null,
    fin             timestamp with time zone not null,
    ajoutes         integer                  not null,
    modifies        integer                  not null,
    retires         integer                  not null,
    rejetees        integer                  not null,
    -- TERMINE ou ECHEC (fichier absent ou illisible : rien n'est modifié)
    statut          varchar(10)              not null,
    message         varchar(300)
);

create index journal_batch_date on catalogue.journal_batch (date_metier, declenchement);

-- Lignes rejetées d'une exécution, avec leur motif.
create table catalogue.ligne_rejetee (
    id           bigint generated by default as identity primary key,
    journal_id   bigint       not null references catalogue.journal_batch (id),
    numero_ligne integer      not null,
    code_isin    varchar(50),
    motif        varchar(200) not null
);

create index ligne_rejetee_journal on catalogue.ligne_rejetee (journal_id);

-- Événement « catalogue mis à jour » : un seul par batch terminé (ADR-001, règle 1). Les étapes suivantes de la
-- nuit (exécution des ordres, TECH-09) attendent cet événement pour la date métier.
create table catalogue.evenement (
    id          bigint generated by default as identity primary key,
    type        varchar(40)              not null,
    date_metier date                     not null,
    journal_id  bigint                   not null references catalogue.journal_batch (id),
    ajoutes     integer                  not null,
    modifies    integer                  not null,
    retires     integer                  not null,
    rejetees    integer                  not null,
    cree_le     timestamp with time zone not null
);
