-- CU-312 (PER-04) : souscription d'un PER par code SMS et premier versement. ADR-001 : module Souscription, tables
-- dans le schéma souscription ; le contrat lui-même est créé par le module Gestion (ModeDeGestion.initialiser).

create schema if not exists souscription;

-- Une souscription par cliente et par produit : premier versement, signature par code SMS, puis contrat créé.
create table souscription.souscription (
    id                bigint generated by default as identity primary key,
    customer_id       uuid                     not null,
    -- PER (AV plus tard, CU-330)
    produit           varchar(3)               not null,
    -- EN_COURS ou SIGNEE
    statut            varchar(10)              not null,
    -- premier versement, en euros (au moins 100 €)
    montant           numeric(15, 2)           not null,
    -- REVENUS, EPARGNE, HERITAGE_DONATION, VENTE_BIEN ou AUTRE
    origine_fonds     varchar(20)              not null,
    -- précision obligatoire pour AUTRE
    origine_precision varchar(200),
    -- compartiment du PER qui reçoit le versement (1 : versements volontaires)
    compartiment      smallint                 not null default 1,
    -- empreinte du code SMS en cours (jamais le code), et sa date d'envoi
    code_hache        varchar(100),
    code_envoye_le    timestamp with time zone,
    -- codes erronés depuis le dernier blocage ; au 3e, signature bloquée 30 minutes
    codes_faux        integer                  not null default 0,
    bloquee_jusqu_au  timestamp with time zone,
    -- contrat créé à la signature
    numero_contrat    varchar(30),
    cree_le           timestamp with time zone not null,
    signee_le         timestamp with time zone,
    unique (customer_id, produit)
);

-- Nouveau mouvement du compte courant : débit d'un versement vers un contrat d'épargne (PER), au nom du contrat.
alter table mouvement drop constraint mouvement_contrepartie;
alter table mouvement
    add constraint mouvement_contrepartie check (
        (type = 'VIREMENT_ENTRANT' and emetteur is not null)
        or (type in ('VIREMENT_SORTANT', 'RECREDIT_VIREMENT')
            and beneficiaire is not null and iban_beneficiaire is not null)
        or (type = 'VERSEMENT_EPARGNE' and beneficiaire is not null)
    );
