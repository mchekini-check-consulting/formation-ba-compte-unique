-- CU-13 (US-08) : création du compte quand la convention est signée, et envoi de l'identifiant
-- (e-mail) et du lien d'activation (SMS).

-- customer_id : profil technique attribué à la signature, gardé lors d'une relance manuelle.
-- creation_* : relances automatiques de la création (jusqu'à 3, à 1 minute d'intervalle).
alter table dossier
    add column customer_id          uuid unique,
    add column creation_tentatives  integer not null default 0,
    add column creation_prochaine_le timestamp with time zone;

-- Un envoi par dossier et par canal : canal, date, résultat, nombre de tentatives.
create table envoi_message (
    id                      bigint generated by default as identity primary key,
    dossier_id              bigint     not null references dossier (id),
    canal                   varchar(5) not null,   -- EMAIL (identifiant), SMS (lien d'activation)
    resultat                varchar(10) not null,  -- ENVOYE, EN_ECHEC (relance prévue), ECHEC
    tentatives              integer    not null,
    dernier_essai_le        timestamp with time zone not null,
    prochaine_tentative_le  timestamp with time zone,
    constraint envoi_message_un_par_canal unique (dossier_id, canal)
);
