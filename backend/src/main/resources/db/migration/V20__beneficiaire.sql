-- CU-146 (US-22) : bénéficiaires de virement d'une cliente (customer_id).
-- Le nom est celui retourné par la vérification (CU-145), jamais modifié ; seul le libellé change.
-- Suppression : le statut passe à SUPPRIME, la ligne est conservée (historique des virements, CU-147).
create table beneficiaire (
    id                     bigint generated by default as identity primary key,
    customer_id            uuid        not null,
    iban                   varchar(34) not null,
    nom_verifie            varchar(70) not null,
    resultat_verification  varchar(20) not null,
    libelle                varchar(70) not null,
    ajoute_le              timestamp with time zone not null,
    statut                 varchar(20) not null,   -- ACTIF, SUPPRIME
    supprime_le            timestamp with time zone
);

-- Pas de doublon : un même IBAN n'est enregistré qu'une fois parmi les bénéficiaires actifs d'une cliente.
create unique index beneficiaire_actif_unique on beneficiaire (customer_id, iban) where statut = 'ACTIF';
create index beneficiaire_customer on beneficiaire (customer_id);

-- Ajout en attente du code SMS : code haché (jamais en clair), valable 5 minutes, à usage unique, 3 essais.
create table ajout_beneficiaire (
    id                     bigint generated by default as identity primary key,
    customer_id            uuid        not null,
    iban                   varchar(34) not null,
    nom_verifie            varchar(70) not null,
    resultat_verification  varchar(20) not null,
    libelle                varchar(70) not null,
    code_hache             varchar(100) not null,
    code_envoye_le         timestamp with time zone not null,
    codes_faux             integer not null default 0,
    statut                 varchar(20) not null    -- EN_ATTENTE, CONFIRME, ANNULE, EXPIRE
);

create index ajout_beneficiaire_customer on ajout_beneficiaire (customer_id);
