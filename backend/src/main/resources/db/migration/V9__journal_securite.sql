-- CU-20 (US-15) : journal de sécurité. Une ligne par accès refusé à un compte : la cliente,
-- la date et l'heure, le compte demandé. Jamais de montant.
create table journal_securite (
    id                        bigint generated by default as identity primary key,
    evenement                 varchar(40) not null,  -- ACCES_COMPTE_REFUSE
    identifiant_connexion_id  bigint      not null references identifiant_connexion (id),
    customer_id               uuid,                  -- vide si la cliente n'a pas encore de compte
    compte_demande            varchar(64) not null,  -- tel que demandé, le compte peut ne pas exister
    survenu_le                timestamp with time zone not null
);
