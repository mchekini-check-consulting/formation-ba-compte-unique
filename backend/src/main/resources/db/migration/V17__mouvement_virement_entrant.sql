-- CU-11 (US-06) et CU-143 (TECH-04) : versement sur le compte courant par virement instantané entrant.
-- mouvement : chaque virement reçu (montant, date, libellé, émetteur) ; le solde du compte augmente du
-- même montant, dans la même transaction. simule : virement du bouchon de test (CU-143), jamais réel.
create table mouvement (
    id                bigint generated by default as identity primary key,
    compte_id         bigint        not null references compte (id),
    type              varchar(20)   not null,  -- VIREMENT_ENTRANT
    montant_centimes  bigint        not null check (montant_centimes > 0),
    libelle           varchar(140)  not null,
    emetteur          varchar(70)   not null,
    simule            boolean       not null default false,
    effectue_le       timestamp with time zone not null
);

create index mouvement_compte on mouvement (compte_id, effectue_le);

-- CU-11 : virement reçu sur un compte clôturé, refusé et renvoyé à l'émetteur (motif SEPA AC04).
-- Le solde n'est pas modifié.
create table retour_virement (
    id                bigint generated by default as identity primary key,
    compte_id         bigint        not null references compte (id),
    montant_centimes  bigint        not null check (montant_centimes > 0),
    libelle           varchar(140)  not null,
    emetteur          varchar(70)   not null,
    motif             varchar(4)    not null,  -- AC04 : compte clôturé
    simule            boolean       not null default false,
    retourne_le       timestamp with time zone not null
);

create index retour_virement_compte on retour_virement (compte_id, retourne_le);
