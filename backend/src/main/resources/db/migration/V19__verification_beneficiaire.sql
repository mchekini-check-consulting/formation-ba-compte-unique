-- CU-145 (TECH-06) : bouchon de vérification du nom du titulaire d'un IBAN, pour ajouter des bénéficiaires
-- (CU-146) sans partenaire réel. Aucune donnée métier : seulement le journal de test et le sélecteur du bouchon.

-- Journal de test : un appel au bouchon = une ligne (date, IBAN vérifié, résultat).
create table verification_beneficiaire_appel (
    id         bigint generated by default as identity primary key,
    appele_le  timestamp with time zone not null,
    iban       varchar(34) not null,
    resultat   varchar(20) not null    -- CORRESPOND, NE_CORRESPOND_PAS, INTROUVABLE, INDISPONIBLE
);

create index verification_beneficiaire_appel_date on verification_beneficiaire_appel (appele_le desc);

-- Sélecteur « Service indisponible » du bouchon : une seule ligne.
create table verification_beneficiaire_bouchon (
    id            smallint primary key check (id = 1),
    indisponible  boolean not null default false
);

insert into verification_beneficiaire_bouchon (id, indisponible) values (1, false);
