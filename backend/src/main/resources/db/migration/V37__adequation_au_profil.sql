-- CU-348 (US-PER-21) et CU-349 (PER-03) : adéquation des unités de compte au profil investisseur. ADR-001 : module
-- Catalogue (fonction publique Adequation), tables dans le schéma catalogue.

-- Rapport d'adéquation : une ligne par proposition de supports à une cliente au profil validé, jamais modifiée.
create table catalogue.rapport_adequation (
    id           bigint generated by default as identity primary key,
    customer_id  uuid                     not null,
    -- PER ou AV
    produit      varchar(3)               not null,
    -- profil investisseur utilisé : PRUDENT, EQUILIBRE ou DYNAMIQUE
    profil       varchar(20)              not null,
    -- codes ISIN proposés, séparés par « | » (vide si aucun)
    supports     text                     not null,
    -- date et heure métier (TECH-12)
    propose_le   timestamp with time zone not null
);

create index rapport_adequation_cliente on catalogue.rapport_adequation (customer_id);

-- Opération refusée à la validation : unité de compte inadaptée au profil en vigueur (aucun montant investi).
create table catalogue.operation_refusee (
    id             bigint generated by default as identity primary key,
    customer_id    uuid                     not null,
    produit        varchar(3)               not null,
    code_isin      varchar(12)              not null,
    -- profil investisseur en vigueur, vide si aucun profil validé
    profil         varchar(20),
    -- VERSEMENT ou ARBITRAGE (et plus tard SOUSCRIPTION)
    type_operation varchar(20)              not null,
    refuse_le      timestamp with time zone not null
);

create index operation_refusee_cliente on catalogue.operation_refusee (customer_id);
