-- CU-10 (US-05) : profil client (KYC) avant une souscription de PER ou d'assurance vie. ADR-001 : module placement,
-- ses tables vivent dans le schéma profil_client ; les autres modules appellent ProfilClientService.

create schema if not exists profil_client;

-- Une ligne par validation du questionnaire (versions en ajout seul : l'ancienne reste consultable avec sa date).
-- Le statut n'est pas stocké : « à compléter » sans ligne, « à revalider » après revalider_le (date métier), sinon « validé ».
create table profil_client.profil_kyc (
    id                        bigint generated by default as identity primary key,
    customer_id               uuid                     not null,
    version                   integer                  not null,
    version_questionnaire     varchar(10)              not null,
    valide_le                 timestamp with time zone not null,
    -- validation + 12 mois
    revalider_le              timestamp with time zone not null,
    -- réponses codées (codes contrôlés par ProfilClientService)
    statut_matrimonial        varchar(20)              not null,
    situation_professionnelle varchar(20)              not null,
    patrimoine                varchar(20)              not null,
    produits_detenus          varchar(20)              not null,
    objectif                  varchar(20)              not null,
    horizon                   varchar(20)              not null,
    reaction_baisse           varchar(20)              not null,
    perte_acceptable          varchar(20)              not null,
    finance_durable           varchar(20)              not null,
    -- montant imprimé sur l'avis d'imposition (plafonds non utilisés compris : peut dépasser 37 680 €)
    plafond_retraite_euros    bigint                   not null check (plafond_retraite_euros >= 0),
    plafond_retraite_annee    integer                  not null,
    tmi                       integer                  not null,
    annee_depart_retraite     integer                  not null,
    -- profil investisseur calculé
    profil_investisseur       varchar(20)              not null,
    score_investisseur        integer                  not null,
    version_regles            varchar(10)              not null,
    profil_calcule_le         timestamp with time zone not null,
    unique (customer_id, version)
);

-- Consentements : une ligne par choix et par version du texte, jamais modifiée.
create table profil_client.consentement (
    id            bigint generated by default as identity primary key,
    customer_id   uuid                     not null,
    type          varchar(40)              not null,
    choix         boolean                  not null,
    version_texte varchar(10)              not null,
    choisi_le     timestamp with time zone not null
);

create index consentement_customer_id on profil_client.consentement (customer_id);
