-- CU-330 (AV-01) : souscription de l'assurance vie dans le même parcours que le PER (module Souscription).
-- Ajouts seulement : le code du PER (V38) continue de fonctionner pendant un déploiement.

-- Le compartiment ne concerne que le PER ; l'âge de la titulaire est enregistré à la signature (assurance vie).
alter table souscription.souscription
    alter column compartiment drop not null,
    add column age_titulaire smallint;

-- Clause bénéficiaire de l'assurance vie, désignation initiale (version 1). Facultative : sans bénéficiaire, le
-- capital entre dans la succession. Les quotes-parts d'une version totalisent 100 %.
create table souscription.beneficiaire (
    id              bigint generated by default as identity primary key,
    souscription_id bigint                   not null references souscription.souscription (id),
    version         integer                  not null default 1,
    -- ordre de saisie
    rang            integer                  not null,
    nom             varchar(70)              not null,
    prenom          varchar(70)              not null,
    date_naissance  date                     not null,
    quote_part_pct  numeric(5, 2)            not null check (quote_part_pct > 0 and quote_part_pct <= 100)
);

create index beneficiaire_souscription on souscription.beneficiaire (souscription_id);
