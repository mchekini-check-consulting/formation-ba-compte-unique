-- CU-380 (TECH-12) : date métier, ADR-001 (un schéma par module). Premier module des placements : ses tables
-- vivent dans le schéma date_metier ; les autres modules ne les lisent jamais, ils appellent DateMetier.

create schema if not exists date_metier;

-- Date simulée en vigueur (environnements de test uniquement) : au plus une ligne. Décalage en secondes par
-- rapport à l'heure réelle de Paris, pour que l'heure continue d'avancer après un changement.
create table date_metier.reglage (
    id                smallint primary key check (id = 1),
    decalage_secondes bigint                   not null,
    modifie_le        timestamp with time zone not null
);

-- Journal des changements de date métier (ajout seul).
create table date_metier.journal_changement (
    id            bigint generated by default as identity primary key,
    ancienne_date timestamp with time zone not null,
    nouvelle_date timestamp with time zone not null,
    -- nom saisi par la testeuse
    auteur        varchar(100)             not null,
    -- heure réelle du changement
    change_le     timestamp with time zone not null
);
