-- CU-28 (US-19) : étape « Mon identité » de l'ouverture d'un Livret A par une cliente connectée.
-- Un contrôle par ouverture : confirmation de la résidence fiscale, coordonnées éventuellement corrigées
-- (le dossier client est mis à jour, la date est gardée ici), puis résultat du contrôle sanctions et
-- personnes politiquement exposées (API Gels des avoirs) avec le nombre d'essais. Aucune donnée personnelle
-- n'est copiée ici : l'identité reste dans le dossier.
create table controle_identite_livret_a (
    id                             bigint generated by default as identity primary key,
    reference                      varchar(64) not null unique,
    dossier_id                     bigint      not null references dossier (id),
    customer_id                    uuid        not null,
    -- EN_COURS, VALIDE, BLOQUE (gel des avoirs), ATTENTE_RESPONSABLE (PPE), EN_ATTENTE (sans réponse)
    statut                         varchar(30) not null,
    residence_fiscale_confirmee_le timestamp with time zone not null,
    coordonnees_modifiees_le       timestamp with time zone,
    -- AUCUNE_CORRESPONDANCE, CORRESPONDANCE_SANCTIONS, CORRESPONDANCE_PEP, SANS_REPONSE
    resultat                       varchar(30),
    tentatives                     integer     not null default 0,
    resultat_le                    timestamp with time zone,
    alerte_conformite_le           timestamp with time zone,
    conseiller_alerte_le           timestamp with time zone,
    responsable_valide_le          timestamp with time zone,
    -- Demande de Livret A ouverte avec ce contrôle : un contrôle ne sert qu'à une ouverture.
    demande_reference              varchar(64),
    cree_le                        timestamp with time zone not null
);

create index controle_identite_livret_a_customer on controle_identite_livret_a (customer_id);
