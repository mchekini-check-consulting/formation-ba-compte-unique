-- CU-88 / CU-13 (US-08) : compte courant créé quand la convention est signée.
-- IBAN de test (CU-88) : FR + clé + banque 99999 + guichet 00001 + compte à 11 chiffres + clé RIB.
-- customer_id : profil technique, jamais montré à la cliente.
create table compte (
    id                        bigint generated by default as identity primary key,
    dossier_id                bigint        not null unique references dossier (id),
    customer_id               uuid          not null unique,
    iban                      varchar(27)   not null unique,
    numero_compte             varchar(11)   not null unique,
    solde                     numeric(15,2) not null default 0,
    statut                    varchar(20)   not null,  -- ACTIF
    ouvert_le                 timestamp with time zone not null,
    identifiant_connexion_id  bigint        not null unique references identifiant_connexion (id)
);
