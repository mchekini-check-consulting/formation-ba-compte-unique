-- CU-31 (US-22) : demande d'ouverture d'un Livret A par une cliente connectée, contrôle de multidétention.
-- Enregistré : attestation sur l'honneur et sa date, choix de partage du détail et sa date, interrogation de
-- l'administration fiscale (référence, date de la première transmission), dernière réponse reçue et sa date,
-- alerte du conseiller quand la réponse n'est pas arrivée sous 2 jours ouvrés, statut de la demande.
-- Aucune identité n'est copiée : elle est lue dans le dossier.
create table demande_livret_a (
    id                       bigint generated by default as identity primary key,
    reference                varchar(64) not null unique,
    dossier_id               bigint      not null references dossier (id),
    customer_id              uuid        not null,
    statut                   varchar(30) not null,  -- EN_COURS_DE_VERIFICATION, OUVERTURE_VALIDEE, LIVRET_A_EXISTANT
    attestation_le           timestamp with time zone not null,
    partage_detail_autorise  boolean     not null,
    choix_partage_le         timestamp with time zone not null,
    interrogation_id         varchar(64),
    interrogation_le         timestamp with time zone,
    reponse_fiscale          varchar(20),           -- AUCUN_LIVRET_A, LIVRET_A_EXISTANT, SANS_REPONSE, INDISPONIBLE
    reponse_le               timestamp with time zone,
    conseiller_alerte_le     timestamp with time zone,
    creee_le                 timestamp with time zone not null
);
create index demande_livret_a_customer on demande_livret_a (customer_id);
create index demande_livret_a_dossier on demande_livret_a (dossier_id);
