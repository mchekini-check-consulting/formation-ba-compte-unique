-- CU-296 (US-22B) : Livret A déjà détenu dans une autre banque. Suite d'une demande au statut LIVRET_A_EXISTANT
-- (CU-31) : la cliente clôture elle-même son ancien livret (dépôt du certificat de clôture sous 3 mois) ou renonce.
-- Nouveaux statuts de demande_livret_a.statut : EN_ATTENTE_CERTIFICAT, CERTIFICAT_A_VERIFIER, ANNULEE, RENONCEE.
-- Uniquement des champs facultatifs ajoutés : les demandes existantes restent valides.
alter table demande_livret_a
    -- détail du livret existant, seulement quand la cliente a autorisé son partage
    add column detail_etablissement   varchar(100),
    add column detail_agence          varchar(100),
    add column detail_date_ouverture  date,
    -- CLOTURE_PAR_CLIENTE, RENONCIATION
    add column suite_choisie          varchar(30),
    add column suite_choisie_le       timestamp with time zone,
    -- réponse de l'administration fiscale + 3 mois
    add column date_limite_certificat date,
    -- e-mail de relance envoyé 15 jours avant la date limite
    add column relance_le             timestamp with time zone,
    -- renonciation, ou date limite dépassée sans certificat validé
    add column annulee_le             timestamp with time zone;

-- Un certificat de clôture par dépôt (historique conservé après un refus). decision vide = à vérifier.
create table certificat_cloture_livret_a (
    id            bigint generated by default as identity primary key,
    demande_id    bigint       not null references demande_livret_a (id),
    fichier       bytea        not null,
    nom_fichier   varchar(255) not null,
    type_fichier  varchar(50)  not null,
    taille        integer      not null,
    depose_le     timestamp with time zone not null,
    -- VALIDE, REFUSE
    decision      varchar(10),
    verifie_par   varchar(100),
    verifie_le    timestamp with time zone,
    motif_refus   varchar(500)
);

create index certificat_cloture_livret_a_demande on certificat_cloture_livret_a (demande_id);
