-- CU-15 : identifiants de connexion, jetons d'activation/réinitialisation, sessions.
-- Aucun secret en clair : mot de passe haché en Argon2id, jetons hachés en SHA-256.
create table identifiant_connexion (
    id                      bigint generated by default as identity primary key,
    identifiant             varchar(32) not null unique,
    mot_de_passe_hache      varchar(255),
    statut                  varchar(30) not null,
    mot_de_passe_defini_le  timestamp with time zone,
    compteur_erreurs        integer not null default 0,
    bloque_jusqu_au         timestamp with time zone,
    cree_le                 timestamp with time zone not null default now(),
    constraint identifiant_connexion_statut_valide
        check (statut in ('EN_ATTENTE_ACTIVATION', 'ACTIF'))
);

create table jeton (
    id                        bigint generated by default as identity primary key,
    identifiant_connexion_id  bigint not null references identifiant_connexion (id),
    type                      varchar(20) not null,
    jeton_hache               varchar(64) not null unique,
    cree_le                   timestamp with time zone not null,
    expire_le                 timestamp with time zone not null,
    utilise_le                timestamp with time zone,
    invalide_le               timestamp with time zone,
    constraint jeton_type_valide check (type in ('ACTIVATION', 'REINITIALISATION'))
);

-- Un seul jeton encore utilisable par client et par type.
create unique index jeton_un_seul_actif
    on jeton (identifiant_connexion_id, type)
    where utilise_le is null and invalide_le is null;

create table session_client (
    id                        bigint generated by default as identity primary key,
    identifiant_connexion_id  bigint not null references identifiant_connexion (id),
    jeton_hache               varchar(64) not null unique,
    cree_le                   timestamp with time zone not null
);
