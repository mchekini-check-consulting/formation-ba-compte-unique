-- CU-382 (TECH-14) : alertes à l'équipe, mécanisme commun à tous les traitements en échec (topic d'erreurs, batch
-- du catalogue, et plus tard exécution des ordres et rapprochement). Module Alertes : schéma alertes ; les autres
-- modules appellent AlertesEquipe, jamais cette table.

create schema if not exists alertes;

-- Journal des alertes (ajout seul) : date métier, origine, message (jamais de donnée personnelle), e-mail envoyé ou
-- non à ALERTE_EQUIPE_EMAIL.
create table alertes.journal (
    id           bigint generated by default as identity primary key,
    date_metier  timestamp with time zone not null,
    origine      varchar(50)              not null,
    message      varchar(500)             not null,
    email_envoye boolean                  not null
);
