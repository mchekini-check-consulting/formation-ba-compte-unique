-- CU-382 (TECH-14) : socle Kafka (ADR-001, révision du 24/11/2026, sections 3 et 3 bis).
-- Les événements sont enregistrés en base dans la même transaction que l'opération (boîte d'envoi, « outbox »),
-- puis publiés dans Kafka par un relais. La base fait foi ; Kafka transporte.

create schema if not exists evenements;

-- Boîte d'envoi : un événement à distribuer, enregistré avec l'opération. Format stable (règle 2 de l'ADR) :
-- identifiant unique, type, clé (numéro de contrat, ISIN, identifiant client ou date métier), date métier,
-- version du format, contenu. publie_le reste vide tant que Kafka n'a pas enregistré le message.
create table evenements.a_distribuer (
    id               bigint generated by default as identity primary key,
    evenement_id     uuid                     not null unique,
    type             varchar(60)              not null,
    topic            varchar(200)             not null,
    cle              varchar(100)             not null,
    date_metier      date                     not null,
    version          integer                  not null,
    -- contenu de l'événement (JSON), petit : identifiants et montants (règle 5)
    contenu          text                     not null,
    cree_le          timestamp with time zone not null,
    publie_le        timestamp with time zone,
    -- tentatives de publication en échec (Kafka indisponible)
    essais           integer                  not null default 0,
    derniere_erreur  varchar(300)
);

-- Le relais lit les événements non publiés dans l'ordre d'enregistrement.
create index a_distribuer_en_attente on evenements.a_distribuer (id) where publie_le is null;

-- Événements déjà traités, par module lecteur (groupe de consommateurs) : un message reçu deux fois n'est traité
-- qu'une seule fois (règle 3 de l'ADR).
create table evenements.traite (
    id           bigint generated by default as identity primary key,
    groupe       varchar(100)             not null,
    evenement_id uuid                     not null,
    traite_le    timestamp with time zone not null,
    unique (groupe, evenement_id)
);

-- Messages en erreur après 3 essais, déposés dans le topic d'erreurs (topic + suffixe .dlt).
create table evenements.en_erreur (
    id           bigint generated by default as identity primary key,
    topic        varchar(200)             not null,
    cle          varchar(100),
    groupe       varchar(100)             not null,
    motif        varchar(300)             not null,
    essais       integer                  not null,
    en_erreur_le timestamp with time zone not null
);

-- Journal back-office : premier module lecteur (groupe <préfixe>-journal). Garde une trace de chaque événement
-- reçu des topics profil-client et catalogue, affichée sur la page de test /test/evenements.
create schema if not exists back_office;

create table back_office.evenement_recu (
    id           bigint generated by default as identity primary key,
    evenement_id uuid                     not null,
    type         varchar(60)              not null,
    topic        varchar(200)             not null,
    cle          varchar(100)             not null,
    date_metier  date                     not null,
    contenu      text                     not null,
    recu_le      timestamp with time zone not null
);

-- Dernier statut de profil publié dans Kafka, par cliente : l'événement « statut du profil modifié » n'est
-- publié qu'au changement (validé, à revalider). Jamais les réponses du questionnaire.
create table profil_client.statut_publie (
    customer_id uuid primary key,
    statut      varchar(20)              not null,
    publie_le   timestamp with time zone not null
);
