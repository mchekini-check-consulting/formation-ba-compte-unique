-- Résultats des bouchons Stripe Identity (CUB-63 pièce, CUB-64 selfie).
-- Aucune image ni donnée d'identité : statut, motif, score, date et concordance par champ.
create table verification_document (
    id                          bigint generated by default as identity primary key,
    dossier_id                  varchar(64)  not null,
    statut                      varchar(30)  not null,
    motif                       varchar(200),
    verifie_le                  timestamp with time zone not null,
    concordance_nom             boolean,
    concordance_prenoms         boolean,
    concordance_date_naissance  boolean,
    concordance_date_expiration boolean
);
create index verification_document_dossier on verification_document (dossier_id);

create table verification_selfie (
    id             bigint generated by default as identity primary key,
    dossier_id     varchar(64) not null,
    resultat       varchar(30) not null,
    score          integer,
    statut_dossier varchar(30) not null,
    verifie_le     timestamp with time zone not null
);
create index verification_selfie_dossier on verification_selfie (dossier_id);
