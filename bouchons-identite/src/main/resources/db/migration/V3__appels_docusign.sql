-- CU-89 : trace de chaque appel au bouchon Docusign (date, code reçu, résultat).
-- Les codes reçus sont des codes de test (111111, 000000, 999999...), jamais un vrai code.
create table appel_docusign (
    id            bigint generated by default as identity primary key,
    dossier_id    varchar(64) not null,
    enveloppe_id  varchar(64) not null,
    operation     varchar(20) not null,  -- ENVOI_ENVELOPPE, SAISIE_CODE, ANNULATION
    code_recu     varchar(6),
    resultat      varchar(30) not null,  -- ENVELOPPE_ENVOYEE, SIGNATURE_VALIDE, CODE_FAUX, CODE_EXPIRE, ANNULATION_DEMANDEE
    appele_le     timestamp with time zone not null
);
create index appel_docusign_enveloppe on appel_docusign (enveloppe_id);
