-- CU-295 : trace de chaque interrogation du bouchon de l'administration fiscale (FICOBA, Livret A).
-- Seulement la référence de la demande, le cas de test, le résultat et la date : jamais l'identité
-- transmise par la banque.
create table interrogation_fiscale (
    id                 bigint generated by default as identity primary key,
    interrogation_id   varchar(64) not null unique,
    demande_id         varchar(64) not null,
    cas_de_test        varchar(20) not null,  -- SANS_LIVRET_A, DETENU_AILLEURS, SANS_REPONSE, INDISPONIBLE
    resultat           varchar(20) not null,  -- AUCUN_LIVRET_A, LIVRET_A_EXISTANT, SANS_REPONSE, INDISPONIBLE
    detail_communique  boolean     not null,
    appele_le          timestamp with time zone not null
);
create index interrogation_fiscale_demande on interrogation_fiscale (demande_id);
